/**
 * Generates a random three-word slug suitable for portal names
 * Format: adjective-connector-noun
 *
 * @param {{
 *   suffix?: string|true
 * }} [options]
 * @returns {string}
 */
export function generateThreeWordSlug(options = {}) {
  const adjective = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)]

  const connector = CONNECTORS[Math.floor(Math.random() * CONNECTORS.length)]

  const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)]

  const suffix =
    options.suffix === true
      ? Math.random().toString(32).slice(2).slice(0, 4)
      : typeof options.suffix === 'string'
      ? options.suffix
      : null

  return [adjective, connector, noun, suffix].filter(Boolean).join('-')
}
