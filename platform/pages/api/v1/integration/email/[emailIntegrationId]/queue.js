/**
 * @typedef {z.infer<typeof InteractPayloadSchema>} InteractPayload
 */
export const InteractPayloadSchema = z.object({
  messageId: z.string().optional(),
  inReplyTo: z.string().optional(),
  to: z.string(),
  from: z.object({
    name: z.string().optional(),
    email: z.string(),
  }),
  subject: z.string(),
  message: z.string(),
  attachments: z
    .array(
      z.object({
        name: z.string(),
        size: z.number(),
        type: z.string(),
        data: z.object({
          url: z.string(),
        }),
      })
    )
    .optional(),
  meta: z.record(z.string()).optional(),

  // @note per-sender monotonic order allocated on the webhook path (see
  // getEmailSupersedeSessionKey / allocateOrder). Threaded through here so the
  // handler can detect it has been superseded by a newer email. Optional for
  // backward-compat with events enqueued before supersede was wired.
  order: z.number().optional(),
})

/**
 * Session key for the supersede + soft-yield mechanism - keyed on the SENDER,
 * not the email thread. Email has no stable per-thread key available on the
 * webhook path (the payload carries only messageId/inReplyTo, no References, and
 * the conversation is resolved by walking the reply chain in the handler), so we
 * treat all rapid emails from one sender as one steerable train of thought. The
 * trade-off: two unrelated threads from the same sender arriving within the
 * bot's response window would cross-supersede (rare; the later wins).
 *
 * @param {string} emailIntegrationId
 * @param {string} email
 * @returns {string}
 */
export function getEmailSupersedeSessionKey(emailIntegrationId, email) {
  return `email-supersede-${emailIntegrationId}-${email}`
}

