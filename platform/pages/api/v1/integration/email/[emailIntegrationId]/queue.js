/**
 * @param {string} emailIntegrationId
 * @param {InteractEvent|SetupEvent|SendEvent|InitiateEvent} event
 * @returns {Promise<void>}
 */
export async function sendEvent(emailIntegrationId, event) {
  switch (true) {
    case event.type === INTERACT_EVENT_TYPE: {
      await parseAsync(InteractPayloadSchema, event.payload, captureInputError)

      break
    }

    case event.type === INITIATE_EVENT_TYPE: {
      await parseAsync(InitiatePayloadSchema, event.payload, captureInputError)

      break
    }

    case event.type === SEND_EVENT_TYPE: {
      await parseAsync(SendPayloadSchema, event.payload, captureInputError)

      break
    }

    case event.type === SETUP_EVENT_TYPE: {
      await parseAsync(SetupPayloadSchema, event.payload, captureInputError)

      break
    }
  }

  if (event.type === INTERACT_EVENT_TYPE) {
    // @note allocate a per-sender order and nudge any in-flight handler for an
    // earlier email from the same sender so it can soft-yield; thread the order
    // into the (already-validated) payload and serialize the dispatch per sender
    // so handlers run one at a time.
    const sessionKey = getEmailSupersedeSessionKey(
      emailIntegrationId,
      event.payload.from.email
    )

    event.payload.order = await allocateOrder(sessionKey)

    await queue(
      `/api/v1/integration/email/${emailIntegrationId}/queue`,
      event,
      { flow: { key: sessionKey, parallel: 1 } }
    )

    return
  }

  await queue(
    `/api/v1/integration/email/${emailIntegrationId}/queue`,
    event,
    {}
  )
}

