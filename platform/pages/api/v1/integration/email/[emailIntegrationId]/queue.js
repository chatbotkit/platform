/**
 * @typedef {{
 *   type: typeof SEND_EVENT_TYPE,
 *   payload: SendPayload
 * }} SendEvent
 *
 * Handles the send event - sends an initial email to a recipient
 * and creates a conversation so that subsequent email replies are tracked.
 *
 * This is used when the outbound text has already been authored.
 *
 * @param {string} emailIntegrationId
 * @param {SendPayload} payload
 * @returns {Promise<void>}
 */
export async function handleSendEvent(emailIntegrationId, payload, context) {
  debug('send', { emailIntegrationId, payload }).log(
    'integration.email.queue.handleSendEvent'
  )

  const integration = await prisma.emailIntegration.findUnique({
    where: {
      id: emailIntegrationId,
    },

    include: {
      user: true,
      bot: true,
    },
  })

  if (!integration) {
    debug(`skipping - integration not found`, { emailIntegrationId }).log(
      'integration.email.queue.handleSendEvent'
    )

    return
  }

  if (!integration.bot) {
    debug(`skipping - no bot configured`).log(
      'integration.email.queue.handleSendEvent'
    )

    return
  }

  if (!(await accountConversationalLimitsOk(integration.user))) {
    debug(`skipping - limits exceeded`, { emailIntegrationId }).log(
      'integration.email.queue.handleSendEvent'
    )

    return
  }

  if (integration.user) {
    updateSessionStore({
      user: userToSessionUser(integration.user),
    })

    setContextUser(integration.user)

    await setupFrontendHostContext(integration.user)
  }

  // @note generate a unique messageId for this initiated email so that when
  // the recipient replies, we can link it back to this conversation via the
  // In-Reply-To header
  const messageId = formatIntegrationMessageId(integration.id)

  // Create a conversation and get/create the session
  const conversationId = await getConversationSessionId({
    integration,
    email: payload.email,
    messageId,
  })

  const { persist, ttlSecs } = resolveSessionDuration(
    integration.sessionDuration
  )

  // @note store the session with messageId so replies can find this conversation
  const messageIdSessionKey = `email-session-${integration.id}-${payload.email}-${messageId}`

  if (persist) {
    await memcache.set(messageIdSessionKey, conversationId, {
      ex: ttlSecs,
    })
  }

  // Get the conversation engine to record the bot's message
  const engine = await getStatefulConversationEngine({
    conversationId,

    options: getEmailConversationEngineOptions({
      integration,
      email: payload.email,
      signal: context?.signal,
      markSignals: context?.markSignals,
    }),
  })

  try {
    // Record the bot's outgoing message in the conversation
    // @note if context is provided, add it as an activity so the bot has
    // background information about the recipient for future interactions
    const contextMessages = payload.context
      ? makeActivityMessagePair(
          '_getEmailContext',
          { email: payload.email },
          { context: payload.context }
        )
      : []

    await engine.addMessages([
      ...contextMessages,
      {
        type: 'bot',
        text: payload.text,
      },
    ])

    // Send the email
    const html = await toHtml(payload.text)

    await sendEmailAction({
      subject: payload.subject,
      content: { text: payload.text, html },
      name: integration.name,
      from: formatIntegrationInbox(integration.id),
      to: payload.email,
      messageId,
    })

    await logEvent({
      user: { id: integration.userId },
      name: 'Email Sent',
      description: `The email was sent to the recipient.`,
      type: 'integration.email.sent',
      relations: {
        emailIntegrationId: integration.id,
        conversationId: conversationId,
      },
      meta: {
        from: formatIntegrationInbox(integration.id),
        to: payload.email,
        subject: payload.subject,
        messageId,
      },
    })
  } finally {
    await engine.dispose()
  }
}

