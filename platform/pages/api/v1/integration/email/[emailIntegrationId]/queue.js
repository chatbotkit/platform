/**
 * @param {{
 *   integration: import('@/prisma/types').EmailIntegration & { bot?: import('@/prisma/types').Bot | null},
 *   name?: string,
 *   email: string,
 *   messageId?: string,
 *   inReplyTo?: string
 * }} options
 * @returns {Promise<string>}
 */
export async function getConversationSessionId({
  integration,
  name,
  email,
  messageId,
  inReplyTo,
}) {
  const { persist, ttlSecs } = resolveSessionDuration(
    integration.sessionDuration
  )

  // derive conversationId from messageId

  const messageIdSessionKey = `email-session-${integration.id}-${email}-${
    messageId || 'default'
  }`

  // @note when `persist` is false (sessionDuration === 0, "no session") we
  // never look up or store the mapping, so every email starts a fresh
  // conversation.
  let conversationId = persist ? await memcache.get(messageIdSessionKey) : null

  if (persist && !conversationId && inReplyTo) {
    const inReplyToSessionKey = `email-session-${integration.id}-${email}-${inReplyTo}`

    conversationId = await memcache.get(inReplyToSessionKey)
  }

  if (!conversationId || !(await hasConversation(conversationId))) {
    let contactId

    {
      if (integration.contactCollection) {
        const contact = await ensureTrustedContact(
          { id: integration.userId },
          {
            name: name,
            email: email,

            meta: {
              app: 'email',
            },
          },
          createContactFingerprint(EMAIL_CONTACT_NAMESPACE, [email])
        )

        contactId = contact.id
      }
    }

    const { id: cid } = await createConversation(integration.userId, {
      contactId,

      ...getConversationDetails({ bot: integration.bot }),

      meta: {
        app: 'email',

        email: {
          integrationId: integration.id,
        },
      },
    })

    conversationId = cid
  }

  if (persist) {
    await memcache.set(messageIdSessionKey, conversationId, {
      ex: ttlSecs,
    })
  }

  return conversationId
}

/**
 * @param {{
 *   integration: Pick<import('@/prisma/types').EmailIntegration, 'attachments' | 'userId'>,
 *   email: string,
 *   userInfo?: import('@/lib/conversation.features').UserInfoFeature['options'],
 *   signal?: AbortSignal,
 *   markSignals?: AbortSignal[],
 *   yieldSignal?: AbortSignal
 * }} options
 */
export function getEmailConversationEngineOptions({
  integration,
  email,
  userInfo,
  signal,
  markSignals,
  yieldSignal,
}) {
  return {
    signal,

    // @note fire-once per-mark signals from the queue monitor; the engine's
    // `timeoutMarks` feature listens to these. NOT cancellation signals

    markSignals,

    // @note cooperative soft-yield: tripped when a newer email from the same
    // sender supersedes this turn, so the engine stops at its next iteration
    // boundary instead of finishing a reply that would be thrown away. Only the
    // interact flow sets this; initiate/send leave it undefined.

    yieldSignal,

    backstoryExtra: `NB: This conversation is happening over email. The user's email address is ${email}.`,

    features: [
      // @note surface who sent the current message to the model for this turn
      // only - the userInfo feature injects it as a soft activity message and
      // never persists it. Only inbound (interact) flows carry a sender.

      ...(userInfo
        ? [{ name: 'userInfo', options: userInfo }]
        : /** @type {any[]} */ ([])),

      // @note record a checkpoint activity into the conversation each time the
      // queue handler crosses a timeout-budget mark (driven by markSignals
      // above), visible to the model on the next turn

      { name: 'timeoutMarks' },

      // @note auth is required to prompt the model to ask the user to
      // re-authenticate any secrets that are missing or expired

      { name: 'auth' },

      // @note time gives the model reliable current date/time awareness
      // instead of guessing from stale training data

      { name: 'time' },

      // @note if attachments are enabled, the model should have the ability
      // to read them from the context and reference them in its responses

      ...(integration.attachments
        ? [{ name: 'attachments' }]
        : /** @type {any[]} */ ([])),
    ],

    userId: integration.userId,
  }
}

/**
 * @typedef {{
 *   type: typeof INTERACT_EVENT_TYPE,
 *   payload: InteractPayload
 * }} InteractEvent
 *
 * @param {string} emailIntegrationId
 * @param {InteractPayload} payload
 * @returns {Promise<void>}
 */
export async function handleInteractEvent(
  emailIntegrationId,
  payload,
  context
) {
  debug(`interact`, { emailIntegrationId, payload })

  const integration = await prisma.emailIntegration.findUnique({
    where: {
      id: emailIntegrationId,
    },

    include: {
      user: true, // @note super important

      bot: true, // @note super important
    },
  })

  if (!integration) {
    debug(`skipping - integration not found`, { emailIntegrationId }).log(
      'integration.email.queue.handleInteractEvent'
    )

    return
  }

  if (!integration.bot) {
    debug(`skipping - no bot configured`).log(
      'integration.email.queue.handleInteractEvent'
    )

    return
  }

  if (!(await accountConversationalLimitsOk(integration.user))) {
    debug(`skipping - limits exceeded`, { emailIntegrationId }).log(
      'integration.email.queue.handleInteractEvent'
    )

    // @note the account is over its usage limits - send a pre-canned reply so
    // the sender gets a visible signal instead of silence. Best-effort: a
    // failed send must not mask the underlying limit condition.
    try {
      const text = messages.limitsReachedReply
      const html = await toHtml(text)

      await sendEmailAction({
        subject: payload.subject || 'Re:',
        content: { text, html },
        name: integration.name,
        from: payload.to,
        to: payload.from.email,
        messageId: payload.messageId,
      })
    } catch (error) {
      debug(`limit reply send failed`, { error }).log(
        'integration.email.queue.handleInteractEvent'
      )
    }

    return
  }

  if (integration.user) {
    updateSessionStore({
      user: userToSessionUser(integration.user),
    })

    setContextUser(integration.user)

    await setupFrontendHostContext(integration.user)
  }

  const conversationId = await getConversationSessionId({
    integration,
    name: payload.from.name,
    email: payload.from.email,
    messageId: payload.messageId,
    inReplyTo: payload.inReplyTo,
  })

  // @note supersede + soft-yield: a newer email from the same sender (a rapid
  // follow-up) should steer this turn rather than queue a second reply. Only
  // meaningful when sessions persist and the webhook allocated an order (events
  // enqueued before supersede was wired carry none).

  const { persist } = resolveSessionDuration(integration.sessionDuration)

  const superseding = persist && payload.order != null

  const supersede = messagingSupersede(
    getEmailSupersedeSessionKey(emailIntegrationId, payload.from.email),
    payload.order ?? 0
  )

  const watch = superseding ? supersede.watch() : null

  const engine = await getStatefulConversationEngine({
    conversationId: conversationId,

    options: getEmailConversationEngineOptions({
      integration,
      email: payload.from.email,
      userInfo: {
        name: payload.from.name,
        email: payload.from.email,
        externalId: payload.from.email,
        source: 'email',
      },
      signal: context?.signal,
      markSignals: context?.markSignals,
      yieldSignal: watch?.yieldSignal,
    }),
  })

  try {
    if (payload.attachments?.length) {
      const maxFileSize = await getMaxFileSize(integration.user)

      const newMessages = (
        await Promise.all(
          payload.attachments.map(async (attachment) => {
            const { attachmentId, name, type } =
              await uploadConversationAttachmentFromURL(
                conversationId,
                attachment.data.url,
                {},
                {
                  maxSize: maxFileSize,
                }
              )

            const {
              request: uploadRequestActivityMessage,
              response: uploadResponseActivityMessage,
            } = makeConversationAttachmentUploadActivityMessages({
              id: attachmentId,
              name: name,
              type: type,
            })

            return [uploadRequestActivityMessage, uploadResponseActivityMessage]
          })
        )
      ).flat()

      await engine.addMessages(newMessages)
    }

    await engine.send(payload.message)

    // @note superseded before generation - the message is now in the
    // conversation, so skip producing a reply that the latest email's handler
    // will coalesce. Cheap guard that avoids a doomed model call.
    if (superseding && (await supersede.isSuperseded())) {
      debug(`superseded before generation - skipping reply`).log(
        'integration.email.queue.handleInteractEvent'
      )

      return
    }

    // @todo provide indication that the bot is typing

    const { text } = await engine.receive()

    // @note the engine soft-yielded mid-turn because a newer email superseded
    // this one; its partial progress is stored, so skip the send and let the
    // latest email's handler produce the reply the user actually sees.
    if (watch?.didYield()) {
      debug(`yielded to a newer email - skipping send`).log(
        'integration.email.queue.handleInteractEvent'
      )

      return
    }

    const html = await toHtml(text)

    await sendEmailAction({
      subject: payload.subject || 'Re:',
      content: { text, html },
      name: integration.name,
      from: payload.to,
      to: payload.from.email,
      messageId: payload.messageId,
    })

    await logEvent({
      user: { id: integration.userId },
      name: 'Email Sent',
      description: `The email was sent to the recipient.`,
      type: 'integration.email.sent',
      relations: {
        emailIntegrationId: integration.id,
        conversationId: conversationId,
      },
      meta: {
        from: payload.to,
        to: payload.from.email,
        messageId: payload.messageId,
      },
    })
  } finally {
    // @note stop watching the sender channel and tear down its subscription;
    // the turn is over (sent, yielded, or errored).
    if (watch) {
      await watch.dispose()
    }

    await engine.dispose()
  }
}

